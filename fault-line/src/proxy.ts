import { createServerClient, type CookieOptions } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";

/**
 * Refreshes the Supabase auth session on every request so server components
 * always see a valid (non-expired) session, and redirects unauthenticated
 * visitors away from gated routes. This is a *routing* convenience only —
 * it is not a security boundary. The real boundary is Row Level Security
 * in Postgres and the server-side admin-role check in /admin/layout.tsx.
 */
export async function proxy(request: NextRequest) {
  let response = NextResponse.next({ request: { headers: request.headers } });

  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        get(name: string) {
          return request.cookies.get(name)?.value;
        },
        set(name: string, value: string, options: CookieOptions) {
          response = NextResponse.next({ request: { headers: request.headers } });
          response.cookies.set({ name, value, ...options });
        },
        remove(name: string, options: CookieOptions) {
          response = NextResponse.next({ request: { headers: request.headers } });
          response.cookies.set({ name, value: "", ...options });
        },
      },
    }
  );

  const {
    data: { user },
  } = await supabase.auth.getUser();

  const gated = ["/feed", "/onboarding", "/account", "/admin"];
  const isGated = gated.some((path) => request.nextUrl.pathname.startsWith(path));

  if (isGated && !user) {
    const url = request.nextUrl.clone();
    url.pathname = "/auth/log-in";
    url.searchParams.set("next", request.nextUrl.pathname);
    return NextResponse.redirect(url);
  }

  return response;
}

export const config = {
  matcher: [
    "/((?!_next/static|_next/image|favicon.ico|icon.svg|assets|api/payments/webhook).*)",
  ],
};
